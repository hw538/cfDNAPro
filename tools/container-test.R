args <- commandArgs(TRUE)
stopifnot(length(args) == 1L, nzchar(args[1]))
suppressPackageStartupMessages(library(cfDNAPro))
stopifnot(as.character(packageVersion("cfDNAPro")) == args[1])
tests <- system.file("tests", "testthat", package = "cfDNAPro", mustWork = TRUE)
result <- testthat::test_dir(tests, reporter = "summary", stop_on_failure = TRUE)
summary <- as.data.frame(result)
stopifnot(!any(summary$error), all(summary$failed == 0L), !any(summary$skipped))
cat("PASS:", sum(summary$passed), "assertions; cfDNAPro", args[1], "\n")
print(sessionInfo())
